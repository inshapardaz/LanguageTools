namespace Nawishta.Mappings;

/// <summary>
/// Represents the supported script systems.
/// </summary>
public enum Script
{
    /// <summary>Romanised/Latin script (used for romanised Urdu and Hindi).</summary>
    Roman,

    /// <summary>Urdu Arabic script (Nastaliq).</summary>
    UrduArabic,

    /// <summary>Hindi Devanagari script.</summary>
    HindiDevanagari
}
